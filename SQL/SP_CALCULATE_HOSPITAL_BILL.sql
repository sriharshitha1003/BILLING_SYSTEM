-- Project: Healthcare Patient and Hospital Billing Management System
CREATE OR REPLACE PROCEDURE "SP_CALCULATE_HOSPITAL_BILL"("P_VISIT_ID" NUMBER(38,0))
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS '
DECLARE
    V_PATIENT_ID NUMBER;
    V_STATUS VARCHAR;
    V_COUNT NUMBER;
    V_CONSULTATION NUMBER DEFAULT 0;
    V_ROOM NUMBER DEFAULT 0;
    V_PROCEDURE NUMBER DEFAULT 0;
    V_LAB NUMBER DEFAULT 0;
    V_MEDICATION NUMBER DEFAULT 0;
    V_DISCOUNT NUMBER DEFAULT 0;
    V_ADJUSTMENT NUMBER DEFAULT 0;
    V_GROSS NUMBER DEFAULT 0;
    V_NET NUMBER DEFAULT 0;
BEGIN

    -- Check whether visit exists
    SELECT COUNT(*)
    INTO :V_COUNT
    FROM PATIENT_VISITS
    WHERE VISIT_ID = :P_VISIT_ID;

    IF (V_COUNT = 0) THEN
        RETURN ''Invalid Visit ID'';
    END IF;

    -- Get patient and visit status
    SELECT PATIENT_ID, VISIT_STATUS
    INTO :V_PATIENT_ID, :V_STATUS
    FROM PATIENT_VISITS
    WHERE VISIT_ID = :P_VISIT_ID;

    IF (V_STATUS <> ''COMPLETED'') THEN
        RETURN ''Visit is not completed'';
    END IF;

    -- Prevent duplicate bills
    SELECT COUNT(*)
    INTO :V_COUNT
    FROM HOSPITAL_BILLS
    WHERE VISIT_ID = :P_VISIT_ID;

    IF (V_COUNT > 0) THEN
        RETURN ''Bill already exists'';
    END IF;

    -- Calculate charges
    SELECT
        COALESCE(SUM(IFF(T.SERVICE_CATEGORY = ''CONSULTATION'',
            C.QUANTITY * T.UNIT_PRICE, 0)), 0),
        COALESCE(SUM(IFF(T.SERVICE_CATEGORY = ''ROOM'',
            C.QUANTITY * T.UNIT_PRICE, 0)), 0),
        COALESCE(SUM(IFF(T.SERVICE_CATEGORY = ''PROCEDURE'',
            C.QUANTITY * T.UNIT_PRICE, 0)), 0),
        COALESCE(SUM(IFF(T.SERVICE_CATEGORY = ''LAB'',
            C.QUANTITY * T.UNIT_PRICE, 0)), 0),
        COALESCE(SUM(IFF(T.SERVICE_CATEGORY = ''MEDICATION'',
            C.QUANTITY * T.UNIT_PRICE, 0)), 0),
        COALESCE(SUM(C.QUANTITY * T.UNIT_PRICE *
            C.DISCOUNT_PERCENT / 100), 0),
        COALESCE(SUM(C.ADJUSTMENT_AMOUNT), 0)
    INTO
        :V_CONSULTATION,
        :V_ROOM,
        :V_PROCEDURE,
        :V_LAB,
        :V_MEDICATION,
        :V_DISCOUNT,
        :V_ADJUSTMENT
    FROM VISIT_CHARGES C
    JOIN SERVICE_TARIFFS T
        ON C.SERVICE_CODE = T.SERVICE_CODE
    WHERE C.VISIT_ID = :P_VISIT_ID
      AND T.IS_ACTIVE = TRUE
      AND T.EFFECTIVE_FROM <= CURRENT_DATE()
      AND (T.EFFECTIVE_TO IS NULL
           OR T.EFFECTIVE_TO >= CURRENT_DATE());

    -- Calculate gross and net amounts
    V_GROSS := V_CONSULTATION + V_ROOM + V_PROCEDURE
               + V_LAB + V_MEDICATION;

    V_NET := V_GROSS - V_DISCOUNT + V_ADJUSTMENT;

    -- Insert bill
    INSERT INTO HOSPITAL_BILLS (
        VISIT_ID, PATIENT_ID, BILL_DATE,
        CONSULTATION_AMOUNT, ROOM_AMOUNT,
        PROCEDURE_AMOUNT, LAB_AMOUNT,
        MEDICATION_AMOUNT, GROSS_AMOUNT,
        DISCOUNT_AMOUNT, ADJUSTMENT_AMOUNT,
        NET_AMOUNT, BILL_STATUS
    )
    VALUES (
        :P_VISIT_ID, :V_PATIENT_ID, CURRENT_DATE(),
        :V_CONSULTATION, :V_ROOM,
        :V_PROCEDURE, :V_LAB,
        :V_MEDICATION, :V_GROSS,
        :V_DISCOUNT, :V_ADJUSTMENT,
        :V_NET, ''GENERATED''
    );

    RETURN ''Bill generated successfully'';

END;
';